import { mkdir, cp, writeFile, rm, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { site } from '../src/config/runtime.mjs';
import { pages, notFoundPage } from '../src/pages/index.mjs';
import { contentSecurityPolicy } from '../src/lib/layout.mjs';
import { minifyCss } from './lib/minify-css.mjs';
import { relativizeHtml } from './lib/relative-urls.mjs';
import { addFallbacks } from './lib/css-fallbacks.mjs';
import { encodeAmpersands } from './lib/html-entities.mjs';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const dist = process.env.MKM_OUT ? path.resolve(process.env.MKM_OUT) : path.join(root, 'dist');
const src = file => path.join(root, 'src', file);

// A public launch needs a domain and at least one real way to contact Monica.
if (!site.previewMode) {
  const problems = [];
  if (!site.siteUrl) problems.push('siteUrl is empty (canonical URLs, sitemap and social image need the final domain)');
  if (!site.whatsappNumber && !site.contactEmail) problems.push('neither whatsappNumber nor contactEmail is set, so enquiries would have nowhere to go');
  if (problems.length) throw new Error(`Cannot build with previewMode off:\n - ${problems.join('\n - ')}`);
}

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await cp(path.join(root, 'public'), dist, { recursive: true });

for (const [filename, render] of pages) {
  const destination = path.join(dist, filename);
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, encodeAmpersands(relativizeHtml(render(), filename)));
}
if (notFoundPage) await writeFile(path.join(dist, '404.html'), encodeAmpersands(notFoundPage()));

// One stylesheet, concatenated in file order.
const styleFiles = (await readdir(src('styles'))).filter(f => f.endsWith('.css')).sort();
const css = (await Promise.all(styleFiles.map(f => readFile(src(`styles/${f}`), 'utf8')))).join('\n');
// site.css lives in assets/, so font URLs become relative to it.
await writeFile(path.join(dist, 'assets/site.css'), minifyCss(addFallbacks(css.replaceAll('url(/assets/', 'url('))));

// Browser modules. site.js is generated so deploy-time overrides reach the browser too.
const js = path.join(dist, 'assets/js');
await mkdir(path.join(js, 'config'), { recursive: true });
await mkdir(path.join(js, 'data'), { recursive: true });
for (const file of await readdir(src('scripts'))) await cp(src(`scripts/${file}`), path.join(js, file));
await cp(src('order.js'), path.join(js, 'order.js'));
await cp(src('data/hair.js'), path.join(js, 'data/hair.js'));
await cp(src('data/services.js'), path.join(js, 'data/services.js'));
const browserSite = Object.fromEntries(Object.entries(site).filter(([key]) => key !== 'siteUrl')); // the browser never needs the origin
await writeFile(path.join(js, 'config/site.js'), `// Generated by scripts/build.mjs from src/config/site.js plus any deploy-time overrides.\nexport const site = Object.freeze(${JSON.stringify(browserSite, null, 2)});\n`);

// Crawl, install and security files.
const origin = site.siteUrl;
const robots = site.previewMode ? 'User-agent: *\nDisallow: /\n' : `User-agent: *\nAllow: /\n${origin ? `Sitemap: ${origin}/sitemap.xml\n` : ''}`;
await writeFile(path.join(dist, 'robots.txt'), robots);
if (origin && !site.previewMode) {
  const urls = pages.map(([, , urlPath, priority]) => `<url><loc>${origin}${urlPath}</loc><priority>${priority}</priority></url>`).join('');
  await writeFile(path.join(dist, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls}</urlset>\n`);
}
await writeFile(path.join(dist, 'manifest.webmanifest'), JSON.stringify({
  name: site.name, short_name: 'MKM', description: site.description, start_url: './', scope: './', display: 'standalone',
  background_color: '#171614', theme_color: '#171614', lang: 'en-AU',
  icons: [
    { src: 'assets/brand/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'assets/brand/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'assets/brand/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2) + '\n');
const csp = contentSecurityPolicy(true);
await writeFile(path.join(dist, '_headers'), [
  '/*', '  X-Content-Type-Options: nosniff', '  Referrer-Policy: strict-origin-when-cross-origin', '  Permissions-Policy: camera=(), microphone=(), geolocation=()', `  Content-Security-Policy: ${csp}`,
  '/assets/*', '  Cache-Control: public, max-age=3600',
  '/assets/fonts/*', '  Cache-Control: public, max-age=604800',
  '/assets/media/*', '  Cache-Control: public, max-age=604800',
  '/assets/hair/*', '  Cache-Control: public, max-age=604800',
  '/assets/editorial/*', '  Cache-Control: public, max-age=604800',
  '/assets/brand/*', '  Cache-Control: public, max-age=604800', '',
].join('\n'));
console.log(`Built ${pages.length} pages${notFoundPage ? ' and a custom 404' : ''} into ${path.relative(root, dist) || '.'}. No runtime dependencies.`);
